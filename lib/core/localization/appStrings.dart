class AppStrings {
  final AppLanguage language;

  const AppStrings(this.language);

  bool get _ru => language == AppLanguage.ru;

  String localize(String source) {
    if (_ru || source.isEmpty) return source;

    final exact = _kkCatalogue[source];
    if (exact != null) return exact;

    return source
        .replaceAll(' отзывов', ' пікір')
        .replaceAll(' отзыв', ' пікір')
        .replaceAll(' дней назад', ' күн бұрын')
        .replaceAll(' дня назад', ' күн бұрын')
        .replaceAll(' день назад', ' күн бұрын')
        .replaceAll('Заказ №', 'Тапсырыс №')
        .replaceAll('Количество: ', 'Саны: ')
        .replaceAll(' за штуку', ' / дана')
        .replaceAll('Ресторанов: ', 'Мейрамханалар: ')
        .replaceAll('Найдено: ', 'Табылды: ')
        .replaceAll('Мин. заказ ', 'Ең төменгі тапсырыс ')
        .replaceAll('Отзывы (', 'Пікірлер (')
        .replaceAll('Уведомления (', 'Хабарландырулар (');
  }

